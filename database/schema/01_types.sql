-- RESCA database: enumerated types
-- Fixed vocabularies live here. Anything agencies may edit (roles, permissions,
-- hazard rules, cost profiles) is a lookup table instead.

-- D1 Identity & Access
CREATE TYPE agency_type        AS ENUM ('GOVERNMENT', 'POLICE', 'EMS', 'FIRE');
CREATE TYPE role_scope         AS ENUM ('PLATFORM', 'AGENCY');
CREATE TYPE user_status        AS ENUM ('INVITED', 'ACTIVE', 'SUSPENDED');
CREATE TYPE device_platform    AS ENUM ('IOS', 'ANDROID', 'WEB');
CREATE TYPE team_type          AS ENUM ('AMBULANCE_UNIT', 'FIRE_ENGINE', 'RESCUE_SQUAD', 'POLICE_PATROL', 'DRONE_CREW', 'COMMAND_UNIT');
CREATE TYPE team_status        AS ENUM ('AVAILABLE', 'DEPLOYED', 'OFF_DUTY');
CREATE TYPE vehicle_type       AS ENUM ('AMBULANCE', 'FIRE_TRUCK', 'PATROL_CAR', 'OFFROAD_4X4', 'BOAT', 'DRONE');
CREATE TYPE vehicle_status     AS ENUM ('AVAILABLE', 'IN_USE', 'OUT_OF_SERVICE');

-- D2 Incidents & Operations
CREATE TYPE disaster_type        AS ENUM ('EARTHQUAKE', 'FLOOD', 'FIRE', 'STORM', 'TSUNAMI', 'LANDSLIDE', 'EXPLOSION', 'OTHER');
CREATE TYPE incident_status      AS ENUM ('ACTIVE', 'CONTAINED', 'CLOSED');
CREATE TYPE participation_role   AS ENUM ('LEAD', 'SUPPORT');
CREATE TYPE participation_status AS ENUM ('INVITED', 'ACTIVE', 'WITHDRAWN');
CREATE TYPE zone_type            AS ENUM ('SECTOR', 'STAGING_AREA', 'SAFE_ZONE', 'EVACUATION_POINT', 'NO_ENTRY');
CREATE TYPE mission_type         AS ENUM ('SEARCH_RESCUE', 'MEDICAL_EVACUATION', 'FIRE_SUPPRESSION', 'ROAD_SECURITY', 'DAMAGE_SURVEY', 'DRONE_SURVEY', 'EVACUATION');
CREATE TYPE mission_status       AS ENUM ('PLANNED', 'ASSIGNED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED');
CREATE TYPE assignment_response  AS ENUM ('PENDING', 'ACCEPTED', 'DECLINED');

-- D3 Imagery & AI
CREATE TYPE capture_source  AS ENUM ('DRONE', 'SATELLITE', 'SIMULATION', 'FIELD_PHONE');
CREATE TYPE capture_phase   AS ENUM ('PRE_EVENT', 'POST_EVENT');
CREATE TYPE session_status  AS ENUM ('UPLOADING', 'PROCESSING', 'READY', 'FAILED');
CREATE TYPE media_kind      AS ENUM ('PHOTO', 'VIDEO_FRAME');
CREATE TYPE spectral_band   AS ENUM ('RGB', 'THERMAL');
CREATE TYPE raster_type     AS ENUM ('ORTHOMOSAIC', 'DSM', 'DTM', 'POINT_CLOUD', 'MESH_3D_TILES', 'DAMAGE_MASK', 'CHANGE_MASK', 'FLOOD_MASK');
CREATE TYPE model_task      AS ENUM ('BUILDING_SEGMENTATION', 'DAMAGE_CLASSIFICATION', 'CHANGE_DETECTION', 'PERSON_DETECTION', 'PERSON_TRACKING', 'ROAD_CONDITION', 'HAZARD_SEGMENTATION', 'FIRE_SMOKE_DETECTION', 'IMAGE_EMBEDDING');
CREATE TYPE job_type        AS ENUM ('STITCH', 'ANALYZE', 'ROUTE', 'REPORT');
CREATE TYPE job_status      AS ENUM ('QUEUED', 'RUNNING', 'SUCCEEDED', 'FAILED');

-- D4a F1 Buildings & Cost
CREATE TYPE occupancy_type     AS ENUM ('RESIDENTIAL', 'COMMERCIAL', 'HOSPITAL', 'SCHOOL', 'GOVERNMENT', 'INDUSTRIAL', 'RELIGIOUS', 'UNKNOWN');
CREATE TYPE construction_type  AS ENUM ('REINFORCED_CONCRETE', 'MASONRY', 'STEEL', 'WOOD', 'UNKNOWN');
CREATE TYPE building_source    AS ENUM ('OSM', 'OVERTURE', 'AI_SEGMENTATION', 'MANUAL');
CREATE TYPE assessment_method  AS ENUM ('AI_BEFORE_AFTER', 'AI_POST_ONLY', 'FIELD_INSPECTION');
CREATE TYPE damage_grade       AS ENUM ('NO_DAMAGE', 'MINOR', 'MAJOR', 'DESTROYED', 'UNCLASSIFIED');
CREATE TYPE review_status      AS ENUM ('PENDING', 'CONFIRMED', 'CORRECTED', 'REJECTED');

-- D4b F2 Roads & Routing
CREATE TYPE road_class      AS ENUM ('PRIMARY', 'SECONDARY', 'RESIDENTIAL', 'SERVICE', 'PATH');
CREATE TYPE road_condition  AS ENUM ('CLEAR', 'DAMAGED', 'DEBRIS', 'FLOODED', 'BLOCKED', 'HAZARD_CLOSED', 'UNKNOWN');
CREATE TYPE route_algorithm AS ENUM ('ASTAR', 'DIJKSTRA');
CREATE TYPE route_status    AS ENUM ('ACTIVE', 'SUPERSEDED', 'INVALIDATED');

-- D4c F3/F4 Persons & Cases
CREATE TYPE visibility_level  AS ENUM ('FULL', 'PARTIAL', 'HEAD_ONLY', 'LIMBS_ONLY');
CREATE TYPE posture           AS ENUM ('STANDING', 'SITTING', 'LYING', 'UNKNOWN');
CREATE TYPE movement_state    AS ENUM ('MOVING', 'STATIONARY', 'UNKNOWN');
CREATE TYPE facility_type     AS ENUM ('HOSPITAL', 'FIELD_HOSPITAL', 'SHELTER', 'FIRE_STATION', 'POLICE_STATION');
CREATE TYPE case_source       AS ENUM ('AI_DETECTION', 'CITIZEN_REQUEST', 'RESPONDER_REPORT');
-- START mass-casualty triage: IMMEDIATE=red, DELAYED=yellow, MINOR=green, EXPECTANT=black
CREATE TYPE triage_category   AS ENUM ('IMMEDIATE', 'DELAYED', 'MINOR', 'EXPECTANT', 'UNTRIAGED');
CREATE TYPE case_status       AS ENUM ('DETECTED', 'VERIFIED', 'ASSIGNED', 'EN_ROUTE', 'ON_SCENE', 'RESCUED', 'TRANSPORTED', 'DECEASED', 'FALSE_ALARM');
CREATE TYPE case_event_type   AS ENUM ('STATUS', 'TRIAGE', 'NOTE', 'PHOTO', 'LOCATION');

-- D4d F5 Hazards & Alerts
CREATE TYPE asset_type    AS ENUM ('POWER_LINE', 'TRANSFORMER', 'SUBSTATION', 'GAS_PIPELINE', 'FUEL_STATION');
CREATE TYPE power_state   AS ENUM ('UNKNOWN', 'ENERGIZED', 'DE_ENERGIZED');
CREATE TYPE hazard_type   AS ENUM ('FLOOD_WATER', 'FIRE', 'SMOKE', 'DOWNED_POWER_LINE', 'GAS_LEAK', 'COLLAPSE_RISK', 'DEBRIS', 'SINKHOLE', 'CHEMICAL_SPILL');
CREATE TYPE hazard_origin AS ENUM ('AI_DETECTED', 'RESPONDER_REPORTED', 'CITIZEN_REPORTED');
CREATE TYPE hazard_status AS ENUM ('SUSPECTED', 'CONFIRMED', 'MITIGATED', 'EXPIRED');
CREATE TYPE rule_operand  AS ENUM ('HAZARD', 'ASSET', 'ROAD');
CREATE TYPE alert_status  AS ENUM ('ACTIVE', 'ACKNOWLEDGED', 'RESOLVED', 'FALSE_ALARM');

-- D5 Field, Citizens, Reports
CREATE TYPE sos_status              AS ENUM ('TRIGGERED', 'ACKNOWLEDGED', 'RESOLVED');
CREATE TYPE citizen_request_type    AS ENUM ('TRAPPED', 'INJURED', 'MEDICAL', 'FIRE', 'HAZARD', 'MISSING_PERSON', 'OTHER');
CREATE TYPE citizen_request_status  AS ENUM ('RECEIVED', 'VERIFYING', 'VERIFIED', 'DUPLICATE', 'REJECTED', 'CONVERTED');
CREATE TYPE notification_kind       AS ENUM ('HAZARD_ALERT', 'SOS', 'ASSIGNMENT', 'ROUTE_CHANGED', 'CASE_UPDATE');
CREATE TYPE report_type             AS ENUM ('SITUATION_REPORT', 'DAMAGE_AND_COST', 'CASUALTY_SUMMARY', 'MISSION_AFTER_ACTION', 'FULL_INCIDENT');
CREATE TYPE report_status           AS ENUM ('DRAFT', 'PENDING_APPROVAL', 'APPROVED', 'PUBLISHED');
CREATE TYPE embedding_source        AS ENUM ('BUILDING_CROP', 'SCENE_TILE');
